#!/usr/bin/env python3
"""Generate data/name_filters.txt from the client DB2 name lists.

Usage: python3 tools/gen_name_filters.py [DBC_DIR] [OUT]
  DBC_DIR  default /srv/forever/data/dbc/enUS (NamesReserved.db2, NamesProfanity.db2)
  OUT      default data/name_filters.txt

Method (the same as the names review of 2026-11-15): the DB2 files store one regex per
string, so the printable strings of the file are the regex list (like `strings -n 3`).
Output rows: `reserved|regex` and `profanity|regex`. tools/check_bot_names.py reads this file
and rejects first names (and pair first names) that match any regex, case-insensitive,
with GNU word anchors \\< and \\> read as \\b. Re-run when the DB2 files change.
"""
import re, sys, os
dbc = sys.argv[1] if len(sys.argv) > 1 else "/srv/forever/data/dbc/enUS"
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "data", "name_filters.txt")
rows = []

def meaningful(s):
    """The string table also holds shared tails and stray fragments of regexes ('[ao]t', 'ere',
    '\\bd', 'gar\\b', 'nder'). Keep a string only if it is a whole pattern: after dropping anchors
    and counting a [..] group as one letter it has 3+ letters when it starts with a word anchor,
    4+ otherwise, and it is not a tail of another string."""
    core = re.sub(r"\\[b<>]", "", s)
    core = re.sub(r"\[[^\]]*\]", "x", core)
    n = len(re.sub(r"[^A-Za-z]", "", core))
    return n >= (3 if s.startswith(("\\b", "\\<")) else 4)

for kind, fn in (("reserved", "NamesReserved.db2"), ("profanity", "NamesProfanity.db2")):
    data = open(os.path.join(dbc, fn), "rb").read()
    seen = set()
    for m in re.finditer(rb"[\x20-\x7e]{3,}", data):
        s = m.group().decode()
        if s in ("WDC5",) or s.startswith("wowstatic_") or s in seen:
            continue
        if not meaningful(s):
            continue
        try:
            re.compile(s.replace("\\<", r"\b").replace("\\>", r"\b"))
        except re.error:
            continue
        seen.add(s); rows.append(f"{kind}|{s}")
    # drop shared string-table tails: a string that is the end of another string of the same file
    tails = {r for r in rows if r.startswith(kind + "|") and any(o != r and o.startswith(kind + "|") and o.endswith(r.split("|", 1)[1]) for o in rows)}
    rows = [r for r in rows if r not in tails]
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by tools/gen_name_filters.py from the client NamesReserved/NamesProfanity DB2 files. Do not edit.\n")
    f.write("\n".join(rows) + "\n")
print(len(rows), "regexes ->", out)
