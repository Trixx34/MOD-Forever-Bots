"""Writes src/heal_ranks_data.h: the rank ladder of each class's single-target heal, with what each rank heals, from the client's DB2 files.

Why: HealDownrank (protocol 28, kCastSpell with dest_x >= 1 names the exact rank) needs to know which rank is enough for a deficit. The rank chains, learn levels and
mana costs are in data/spell_costs.txt (made by the core); what a rank heals is the Heal effect (SpellEffect.db2, effect 10, EffectBasePoints + 1 = the average of the
range, EffectRealPointsPerLevel is ignored: it only matters above the spell's own level). Spell power bonuses are not included. A hotfix row of the server database
overrides the client file; this tool does not read the database, so a rank the server changed is off by that much until the file is made again with the rows applied.

    python3 -I tools/heal_ranks_from_db2.py --dbc /srv/forever/data/dbc/enUS --costs data/spell_costs.txt > src/heal_ranks_data.h
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import db2_reader  # noqa: E402

# (chain id, first rank's spell id, name): the ladders HealSpellFor offers (class 5 priest below level 16: Lesser Heal, from 16: Heal; 2 paladin; 7 shaman; 11 druid)
CHAINS = (("kChainLesserHeal", 2050, "Lesser Heal"), ("kChainHeal", 2054, "Heal"), ("kChainHolyLight", 635, "Holy Light"),
          ("kChainHealingWave", 331, "Healing Wave"), ("kChainHealingTouch", 5185, "Healing Touch"))
# The rank chains of data/spell_costs.txt have two gaps (the core's rank groups split there): Heal 2055 -> 6063 and Holy Light 10328 -> 10329 (next_rank 1313352, a
# Forever spell the file has no row for); the next ranks are the same family, icon and name at the next level.
EXTRA_LINKS = {2055: 6063, 10328: 10329}
F_EFFECT, F_BASE_POINTS = 3, 22
EFFECT_HEAL = 10


def read_costs(path):
    rows = {}
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            if line.startswith("#"):
                continue
            p = line.rstrip("\n").split("\t")
            if len(p) >= 8 and p[2] == "0":   # power type 0: mana
                rows.setdefault(int(p[0]), (int(p[1]), int(p[3]), int(p[6]), p[7]))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dbc", required=True)
    ap.add_argument("--costs", required=True)
    args = ap.parse_args()
    costs = read_costs(args.costs)
    table = db2_reader.read_table(os.path.join(args.dbc, "SpellEffect.db2"), skip_encrypted=True)
    parents = db2_reader.read_table.parents
    heal = {}
    for rid, v in table.items():
        sid = parents.get(rid)
        if sid and v[F_EFFECT] == EFFECT_HEAL and v[1] == 0:
            heal.setdefault(sid, int(round(db2_reader.as_float(v[F_BASE_POINTS]))) + 1)
    out = ["// SPDX-License-Identifier: GPL-2.0-or-later",
           "// Generated by tools/heal_ranks_from_db2.py (client data, data/spell_costs.txt): do not edit. The rank ladders of the single-target heals (HealSpellFor), lowest rank first:",
           "// spell id, the level it is learned at, its mana cost and what it heals on average (base points + 1, no spell power).",
           "#pragma once", "#include <cstdint>", "",
           "namespace heal_ranks", "{", "struct Rank { std::uint32_t Chain; std::uint32_t Spell; std::uint32_t Level; std::uint32_t Mana; std::uint32_t Amount; };",
           "enum : std::uint32_t { " + ", ".join(f"{name} = {i}" for i, (name, _, _) in enumerate(CHAINS)) + " };",
           "inline constexpr Rank kRanks[] = {"]
    for name, first, title in CHAINS:
        spell, seen = first, set()
        while spell and spell not in seen and spell in costs:
            seen.add(spell)
            level, mana, nxt, cname = costs[spell]
            if spell not in heal:
                sys.exit(f"{spell} ({cname}) has no heal effect in SpellEffect.db2 (or it is in an encrypted section)")
            out.append(f"    {{ {name}, {spell}, {level}, {mana}, {heal[spell]} }},   // {cname}")
            spell = EXTRA_LINKS.get(spell) or (nxt if nxt in costs else 0)
    out += ["};", "}"]
    print("\n".join(out))


main()
